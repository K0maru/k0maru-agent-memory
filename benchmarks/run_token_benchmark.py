#!/usr/bin/env python3
"""
Token Reduction Benchmark Engine for k0maru-agent-memory.

Evaluates token consumption and reduction ratios (TRR %) of raw command logs
versus symbolic Mermaid graphs generated by `k0maru offload`.

Uses tiktoken with `cl100k_base` (GPT-4 / Claude / standard LLM baseline)
and `o200k_base` (GPT-4o) tokenizers.
"""

import argparse
import csv
import glob
import os
import subprocess
import sys
import warnings

# Filter harmless SSL warning on macOS default python / urllib3
warnings.filterwarnings("ignore", message=".*urllib3 v2 only supports OpenSSL.*")

# Automatically discover and add repository virtualenv site-packages if needed
_REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
for _pattern in [
    os.path.join(_REPO_ROOT, ".venv", "lib", "python*", "site-packages"),
    os.path.join(_REPO_ROOT, "benchmarks", ".venv", "lib", "python*", "site-packages"),
]:
    for _site_dir in glob.glob(_pattern):
        if _site_dir not in sys.path:
            sys.path.insert(0, _site_dir)

try:
    import tiktoken
except ImportError as err:
    print(f"Error: tiktoken is not installed. Please run 'pip install -r benchmarks/requirements.txt'. ({err})", file=sys.stderr)
    sys.exit(1)


def find_k0maru_binary(explicit_path=None):
    """Locate the k0maru executable binary."""
    candidates = []
    if explicit_path:
        candidates.append(explicit_path)
    if os.environ.get("K0MARU_BIN"):
        candidates.append(os.environ["K0MARU_BIN"])
    
    candidates.extend([
        os.path.join(_REPO_ROOT, "target", "release", "k0maru"),
        os.path.join(_REPO_ROOT, "target", "debug", "k0maru"),
        "k0maru",
    ])

    for candidate in candidates:
        if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return os.path.abspath(candidate)
        # Check in PATH for plain command names
        if not os.path.isabs(candidate) and "/" not in candidate:
            which_path = subprocess.run(["which", candidate], capture_output=True, text=True).stdout.strip()
            if which_path and os.path.isfile(which_path) and os.access(which_path, os.X_OK):
                return which_path

    raise FileNotFoundError(
        f"Could not find k0maru binary. Checked candidates: {candidates}. "
        "Run `cargo build --release` first or provide --bin."
    )


def offload_log(k0maru_bin, raw_content, refs_dir=None):
    """Pipe raw log content into `k0maru offload` and capture stdout."""
    cmd = [k0maru_bin, "offload"]
    if refs_dir:
        cmd.extend(["--refs-dir", refs_dir])

    proc = subprocess.run(
        cmd,
        input=raw_content.encode("utf-8"),
        capture_output=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(
            f"k0maru offload failed with exit code {proc.returncode}:\n{proc.stderr.decode('utf-8', errors='replace')}"
        )
    return proc.stdout.decode("utf-8", errors="replace")


def evaluate_fixture(fixture_path, k0maru_bin, enc_cl100k, enc_o200k, refs_dir=None):
    """Evaluate token reduction for a single fixture file."""
    with open(fixture_path, "r", encoding="utf-8", errors="replace") as f:
        raw_text = f.read()

    raw_lines = len(raw_text.splitlines())
    offloaded_text = offload_log(k0maru_bin, raw_text, refs_dir=refs_dir)

    raw_tokens_cl100k = len(enc_cl100k.encode(raw_text))
    offloaded_tokens_cl100k = len(enc_cl100k.encode(offloaded_text))
    trr_cl100k = (
        (raw_tokens_cl100k - offloaded_tokens_cl100k) / raw_tokens_cl100k * 100.0
        if raw_tokens_cl100k > 0
        else 0.0
    )

    raw_tokens_o200k = len(enc_o200k.encode(raw_text))
    offloaded_tokens_o200k = len(enc_o200k.encode(offloaded_text))
    trr_o200k = (
        (raw_tokens_o200k - offloaded_tokens_o200k) / raw_tokens_o200k * 100.0
        if raw_tokens_o200k > 0
        else 0.0
    )

    return {
        "fixture": os.path.basename(fixture_path),
        "raw_lines": raw_lines,
        "raw_tokens_cl100k": raw_tokens_cl100k,
        "offloaded_tokens_cl100k": offloaded_tokens_cl100k,
        "token_reduction_ratio_pct": round(trr_cl100k, 2),
        "raw_tokens_o200k": raw_tokens_o200k,
        "offloaded_tokens_o200k": offloaded_tokens_o200k,
        "reduction_o200k_pct": round(trr_o200k, 2),
    }


def main():
    parser = argparse.ArgumentParser(
        description="Run token reduction benchmark against k0maru offload engine."
    )
    parser.add_argument(
        "--bin",
        default=None,
        help="Path to k0maru binary (defaults to target/release/k0maru or target/debug/k0maru)",
    )
    parser.add_argument(
        "--fixtures-dir",
        default=os.path.join(_REPO_ROOT, "benchmarks", "fixtures"),
        help="Path to benchmark fixtures directory",
    )
    parser.add_argument(
        "--output-csv",
        default=os.path.join(_REPO_ROOT, "benchmarks", "results", "token_savings.csv"),
        help="Output CSV file path",
    )
    parser.add_argument(
        "--assert-min-reduction",
        type=float,
        default=None,
        help="Assert minimum reduction ratio percentage (e.g. 60.0). Exit 1 if any fixture falls below this.",
    )

    args = parser.parse_args()

    k0maru_bin = find_k0maru_binary(args.bin)
    print(f"🔬 Using k0maru binary: {k0maru_bin}")

    if not os.path.isdir(args.fixtures_dir):
        print(f"❌ Fixtures directory not found: {args.fixtures_dir}", file=sys.stderr)
        sys.exit(1)

    fixture_files = sorted(glob.glob(os.path.join(args.fixtures_dir, "*.log")))
    if not fixture_files:
        print(f"❌ No .log files found in fixtures directory: {args.fixtures_dir}", file=sys.stderr)
        sys.exit(1)

    print(f"📂 Found {len(fixture_files)} fixtures in {args.fixtures_dir}")
    print("⏳ Initializing tiktoken encoders ('cl100k_base' & 'o200k_base')...")
    enc_cl100k = tiktoken.get_encoding("cl100k_base")
    enc_o200k = tiktoken.get_encoding("o200k_base")

    results = []
    # Dedicated temp refs directory for clean benchmark isolated storage
    bench_refs = os.path.join(_REPO_ROOT, ".scratch", "benchmark_refs")
    os.makedirs(bench_refs, exist_ok=True)

    for fix_file in fixture_files:
        res = evaluate_fixture(
            fix_file,
            k0maru_bin,
            enc_cl100k,
            enc_o200k,
            refs_dir=bench_refs,
        )
        results.append(res)

    # Save to CSV
    os.makedirs(os.path.dirname(args.output_csv), exist_ok=True)
    fieldnames = [
        "fixture",
        "raw_lines",
        "raw_tokens_cl100k",
        "offloaded_tokens_cl100k",
        "token_reduction_ratio_pct",
        "raw_tokens_o200k",
        "offloaded_tokens_o200k",
        "reduction_o200k_pct",
    ]
    with open(args.output_csv, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(results)
    print(f"💾 Results exported to: {args.output_csv}\n")

    # Format output table
    print("=========================================================================================================")
    print("📊 K0MARU TOKEN REDUCTION BENCHMARK RESULTS")
    print("=========================================================================================================")
    print(f"{'Fixture':<26} | {'Lines':>6} | {'Raw(cl100k)':>11} | {'Offload':>8} | {'TRR %':>8} | {'Raw(o200k)':>11} | {'Offload':>8} | {'TRR %':>8}")
    print("-" * 105)

    tot_raw_cl100k = 0
    tot_off_cl100k = 0
    tot_raw_o200k = 0
    tot_off_o200k = 0
    min_observed_trr = 100.0

    for r in results:
        tot_raw_cl100k += r["raw_tokens_cl100k"]
        tot_off_cl100k += r["offloaded_tokens_cl100k"]
        tot_raw_o200k += r["raw_tokens_o200k"]
        tot_off_o200k += r["offloaded_tokens_o200k"]
        min_observed_trr = min(min_observed_trr, r["token_reduction_ratio_pct"])

        print(
            f"{r['fixture']:<26} | {r['raw_lines']:>6} | {r['raw_tokens_cl100k']:>11} | {r['offloaded_tokens_cl100k']:>8} | {r['token_reduction_ratio_pct']:>7.2f}% | {r['raw_tokens_o200k']:>11} | {r['offloaded_tokens_o200k']:>8} | {r['reduction_o200k_pct']:>7.2f}%"
        )

    overall_trr_cl100k = (tot_raw_cl100k - tot_off_cl100k) / tot_raw_cl100k * 100.0 if tot_raw_cl100k else 0.0
    overall_trr_o200k = (tot_raw_o200k - tot_off_o200k) / tot_raw_o200k * 100.0 if tot_raw_o200k else 0.0

    print("-" * 105)
    print(
        f"{'OVERALL AVERAGE':<26} | {'-':>6} | {tot_raw_cl100k:>11} | {tot_off_cl100k:>8} | {overall_trr_cl100k:>7.2f}% | {tot_raw_o200k:>11} | {tot_off_o200k:>8} | {overall_trr_o200k:>7.2f}%"
    )
    print("=========================================================================================================\n")

    # Check minimum reduction assertion
    if args.assert_min_reduction is not None:
        threshold = args.assert_min_reduction
        print(f"🎯 Asserting minimum Token Reduction Ratio >= {threshold:.1f}%...")
        failed_fixtures = [
            r for r in results if r["token_reduction_ratio_pct"] < threshold
        ]
        if failed_fixtures:
            print(f"❌ ASSERTION FAILED: {len(failed_fixtures)} fixture(s) fell below {threshold:.1f}% TRR:", file=sys.stderr)
            for f in failed_fixtures:
                print(f"   • {f['fixture']}: {f['token_reduction_ratio_pct']:.2f}% < {threshold:.1f}%", file=sys.stderr)
            sys.exit(1)
        else:
            print(f"✅ PASSED: All fixtures achieved >= {threshold:.1f}% token reduction (lowest was {min_observed_trr:.2f}%).\n")


if __name__ == "__main__":
    main()
